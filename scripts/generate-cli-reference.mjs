#!/usr/bin/env node
// Generate docs/reference/cli.md from the citty command tree exported by the CLI.
// Walks the `main` command tree in-process (no per-command subprocess spawning),
// so the reference stays in sync with the actual command definitions.
//
// Usage: npm run docs:cli   (runs `tsc` first, then this script against dist/)

import { mkdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

// Prevent the CLI module from launching runMain when we import it.
process.env.SCALE_CLI_NO_AUTORUN = '1'

const here = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(here, '..')
const cliEntry = join(repoRoot, 'dist', 'api', 'cli.js')

const mod = await import(pathToFileURL(cliEntry).href)
const main = mod.main
if (!main) {
  console.error('error: dist/api/cli.js does not export `main`. Run `npm run build` first.')
  process.exit(1)
}

async function resolveValue(value) {
  return typeof value === 'function' ? await value() : value
}

function formatArgs(args) {
  const entries = Object.entries(args ?? {})
  if (entries.length === 0) return ''
  const lines = ['', '| Option | Type | Default | Description |', '|---|---|---|---|']
  for (const [name, spec] of entries) {
    const type = spec?.type ?? 'string'
    const def = spec?.default === undefined ? '' : '`' + String(spec.default) + '`'
    const desc = (spec?.description ?? '').replace(/\|/g, '\\|')
    lines.push(`| \`--${name}\` | ${type} | ${def} | ${desc} |`)
  }
  return lines.join('\n')
}

const rows = []
const toc = []

async function walk(command, pathParts, depth) {
  const meta = await resolveValue(command.meta)
  const args = await resolveValue(command.args)
  const subCommands = await resolveValue(command.subCommands)

  const name = pathParts.join(' ')
  if (name) {
    const anchor = name.replace(/\s+/g, '-')
    toc.push(`${'  '.repeat(Math.max(0, depth - 1))}- [\`scale ${name}\`](#scale-${anchor})`)
    const heading = '#'.repeat(Math.min(6, depth + 1))
    const block = [`${heading} \`scale ${name}\``, '']
    if (meta?.description) block.push(meta.description, '')
    const argsTable = formatArgs(args)
    if (argsTable) block.push(argsTable, '')
    rows.push(block.join('\n'))
  }

  if (subCommands) {
    for (const key of Object.keys(subCommands)) {
      await walk(await resolveValue(subCommands[key]), [...pathParts, key], depth + 1)
    }
  }
}

const rootMeta = await resolveValue(main.meta)
const rootSubs = await resolveValue(main.subCommands)
for (const key of Object.keys(rootSubs ?? {})) {
  await walk(await resolveValue(rootSubs[key]), [key], 1)
}

const header = [
  '# SCALE Engine CLI Reference',
  '',
  '> Auto-generated by `scripts/generate-cli-reference.mjs`. Do not edit by hand.',
  '> Regenerate with `npm run docs:cli`.',
  '',
  `Version: \`${rootMeta?.version ?? 'unknown'}\``,
  '',
  rootMeta?.description ?? '',
  '',
  '## Commands',
  '',
  toc.join('\n'),
  '',
  '---',
  '',
].join('\n')

const outDir = join(repoRoot, 'docs', 'reference')
mkdirSync(outDir, { recursive: true })
const outFile = join(outDir, 'cli.md')
writeFileSync(outFile, header + rows.join('\n\n') + '\n', 'utf-8')

const commandCount = rows.length
console.log(`Generated ${outFile} (${commandCount} commands)`)
